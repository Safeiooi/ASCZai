/** สร้างบล็อกหลักฐานจากผลค้นหา พร้อมกติกาห้ามแต่ง */
export function buildEvidenceBlock(
  citations: { docTitle: string; heading: string | null; snippet: string; source: string | null }[],
): string {
  if (citations.length === 0) {
    return `หลักฐานจากฐานความรู้: (ไม่พบหลักฐานที่เกี่ยวข้อง)
กติกา: ฐานความรู้ยังไม่มีข้อมูลยืนยันสำหรับคำถามนี้ ให้บอกตามจริงว่าไม่พบหลักฐาน แล้วเสนอการตรวจทั่วไปและสิ่งที่ควรถาม/ขอเพิ่มเท่านั้น ห้ามเดาข้อเท็จจริงของ PEAK`
  }
  const lines = citations.map(
    (c, i) => `[${i + 1}] เอกสาร: ${c.docTitle}${c.heading ? ` | ส่วน: ${c.heading}` : ''}${c.source ? ` | ที่มา: ${c.source}` : ''}\nเนื้อหา: ${c.snippet}`,
  )
  return `หลักฐานจากฐานความรู้ (${citations.length} รายการ):
${lines.join('\n\n')}
กติกา: ใช้เฉพาะข้อเท็จจริงที่ปรากฏในหลักฐานข้างต้นและอ้างเลข [n] กำกับ หากหลักฐานไม่พอหรือขัดกันให้แจ้งตรง ๆ ห้ามแต่งเพิ่ม`
}
